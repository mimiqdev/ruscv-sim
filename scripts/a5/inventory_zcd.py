"""Verify the frozen Zcd selection against every pinned ACT4 Zcd source.

This is deliberately specific to ACT4 4.0.0 headers and reuses the exact
metadata parser from inventory.py, so the frozen RV64I inventory's parse
semantics and this selection cannot drift apart. Unknown header syntax,
revisions or coverage groups require review, exactly as there.

Contract D11: every source in `tests/rv64i/Zcd` at the pinned revision, and
nothing else. The four Zcd sources require `I`, `F`, `D` and `Zcd`, so they run
under `--isa rv64imafdc` with the Zcd UDB and Sail configuration.
"""
import argparse
import json
from pathlib import Path

from inventory import build, sha256

MANIFEST = Path("docs/verification/a5-zcd-source-inventory.json")
PROFILE = "a5-rv64imafdc-zcd-nontrapping-proposal-v1"
DIRECTORY = "Zcd"


def selected(manifest):
    identifiers = [s["source"] for s in manifest["sources"]]
    if len(identifiers) != len(set(identifiers)):
        raise ValueError("duplicate Zcd inventory source")
    sources = [s["source"] for s in manifest["sources"] if s["disposition"] == "include"]
    if not sources or len(sources) != len(set(sources)):
        raise ValueError("empty or duplicate selected Zcd sources")
    return sources


def build_zcd(upstream):
    """Build the expected Zcd manifest from the pinned tree, fail-closed."""
    expected = build(upstream)
    # The frozen 51-case RV64I manifest is regenerated by inventory.py and is
    # not touched here; only the Zcd subdirectory is carved out of the same
    # pinned build so header parsing stays shared.
    sources = []
    for source in expected["sources"]:
        parts = Path(source["source"]).parts
        if len(parts) < 4 or parts[:3] != ("tests", "rv64i", DIRECTORY):
            continue
        if (source["required_extensions"] != ["D", "F", "I", "Zcd"]
                or source["params"] != {"MXLEN": 64}
                or source["march"] != "rv64ifd_zicsr_zcd"):
            raise ValueError(f"unreviewed Zcd source: {source['source']}")
        record = dict(source)
        record["disposition"] = "include"
        record["reason"] = "required-zcd"
        record["coverage_consequence"] = (
            "Nontrapping RV64 Zcd compressed double-precision load/store coverage "
            "under --isa rv64imafdc; failure remains a blocker.")
        sources.append(record)
    if not sources:
        raise ValueError("empty upstream Zcd inventory")
    sources.sort(key=lambda s: s["source"])
    environment_headers = {
        f"tests/env/{path.name}": sha256(path)
        for path in sorted((upstream / "tests/env").iterdir()) if path.is_file()
    }
    return {
        "schema_version": 1,
        "status": expected["status"],
        "act4_commit": expected["act4_commit"],
        "scope": "all tracked tests/rv64i/Zcd/**/*.S at the pinned revision",
        "profile": PROFILE,
        # The frozen selection manifest is this profile's own document; the
        # accounting plan pins it instead of the unrelated RV64I proposal.
        "profile_document": str(MANIFEST),
        "counts": {"required-zcd": len(sources)},
        "sources": sources,
        "environment_headers": environment_headers,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, default=Path(".a5/upstream"))
    parser.add_argument("--write", action="store_true", help="regenerate proposal for review, never freeze")
    args = parser.parse_args()
    actual = build_zcd(args.upstream)
    selected(actual)
    if args.write:
        MANIFEST.write_text(json.dumps(actual, indent=2) + "\n")
    elif json.loads(MANIFEST.read_text()) != actual:
        raise ValueError("Zcd selection differs from checked-in manifest")
    print(json.dumps({"status": actual["status"], "sources": len(actual["sources"]),
                      "counts": actual["counts"]}))


if __name__ == "__main__":
    main()
