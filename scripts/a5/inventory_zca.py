"""Verify the frozen Zca selection against every pinned ACT4 Zca source.

This is deliberately specific to ACT4 4.0.0 headers and reuses the exact
metadata parser from inventory.py, so the frozen 51-case inventory's parse
semantics and this selection cannot drift apart. Unknown header syntax,
revisions or coverage groups require review, exactly as there.
"""
import argparse
import json
from pathlib import Path

from inventory import build, metadata, sha256

MANIFEST = Path("docs/verification/a5-zca-source-inventory.json")
PROFILE = "a5-rv64imac-zca-nontrapping-proposal-v1"


def selected(manifest):
    identifiers = [s["source"] for s in manifest["sources"]]
    if len(identifiers) != len(set(identifiers)):
        raise ValueError("duplicate Zca inventory source")
    sources = [s["source"] for s in manifest["sources"] if s["disposition"] == "include"]
    if not sources or len(sources) != len(set(sources)):
        raise ValueError("empty or duplicate selected Zca sources")
    return sources


def build_zca(upstream):
    """Build the expected Zca manifest from the pinned tree, fail-closed."""
    expected = build(upstream)
    # The frozen 51-case RV64I manifest is regenerated by inventory.py and is
    # not touched here; only the Zca subdirectory is carved out of the same
    # pinned build so header parsing stays shared.
    zca = [dict(s) for s in expected["sources"]
           if s["source"].startswith("tests/rv64i/Zca/")]
    if not zca:
        raise ValueError("empty upstream Zca inventory")
    for source in zca:
        if source["required_extensions"] != ["I", "Zca"] or source["params"] != {"MXLEN": 64}:
            raise ValueError(f"unreviewed Zca source: {source['source']}")
        source["disposition"] = "include"
        source["reason"] = "required-zca"
        source["coverage_consequence"] = (
            "Nontrapping RV64 Zca compressed-instruction coverage under --isa rv64imac; "
            "failure remains a blocker.")
    zca.sort(key=lambda s: s["source"])
    environment_headers = {
        f"tests/env/{path.name}": sha256(path)
        for path in sorted((upstream / "tests/env").iterdir()) if path.is_file()
    }
    return {
        "schema_version": 1,
        "status": expected["status"],
        "act4_commit": expected["act4_commit"],
        "scope": "all tracked tests/rv64i/Zca/**/*.S at the pinned revision",
        "profile": PROFILE,
        # The frozen selection manifest is this profile's own document; the
        # accounting plan pins it instead of the unrelated RV64I proposal.
        "profile_document": str(MANIFEST),
        "counts": {"required-zca": len(zca)},
        "sources": zca,
        "environment_headers": environment_headers,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, default=Path(".a5/upstream"))
    parser.add_argument("--write", action="store_true", help="regenerate proposal for review, never freeze")
    args = parser.parse_args()
    actual = build_zca(args.upstream)
    selected(actual)
    if args.write:
        MANIFEST.write_text(json.dumps(actual, indent=2) + "\n")
    elif json.loads(MANIFEST.read_text()) != actual:
        raise ValueError("Zca selection differs from checked-in manifest")
    print(json.dumps({"status": actual["status"], "sources": len(actual["sources"]),
                      "counts": actual["counts"]}))


if __name__ == "__main__":
    main()
