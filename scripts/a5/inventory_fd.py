"""Verify the frozen F/D selection against every pinned ACT4 F and D source.

This is deliberately specific to ACT4 4.0.0 headers and reuses the exact
metadata parser from inventory.py, so the frozen RV64I inventory's parse
semantics and this selection cannot drift apart. Unknown header syntax,
revisions or coverage groups require review, exactly as there.

Contract D11: every source in `tests/rv64i/F` and `tests/rv64i/D` at the
pinned revision, and nothing else. `MisalignF` and `MisalignD` carry the same
`REQUIRED_EXTENSIONS` as their natural-alignment neighbours, so the directory
is the exclusion mechanism here; a source outside the two directories is
rejected rather than silently carried.
"""
import argparse
import json
from pathlib import Path

from inventory import build, sha256

MANIFEST = Path("docs/verification/a5-fd-source-inventory.json")
PROFILE = "a5-rv64imafd-nontrapping-proposal-v1"

# directory -> (required extensions, march, disposition reason). The
# extension lists are compared in the parser's sorted order, exactly as
# inventory.py returns them for the frozen RV64I manifest.
DIRECTORIES = {
    "F": (["F", "I"], "rv64if_zicsr", "required-f"),
    "D": (["D", "F", "I"], "rv64ifd_zicsr", "required-d"),
}


def selected(manifest):
    identifiers = [s["source"] for s in manifest["sources"]]
    if len(identifiers) != len(set(identifiers)):
        raise ValueError("duplicate F/D inventory source")
    sources = [s["source"] for s in manifest["sources"] if s["disposition"] == "include"]
    if not sources or len(sources) != len(set(sources)):
        raise ValueError("empty or duplicate selected F/D sources")
    return sources


def build_fd(upstream):
    """Build the expected F/D manifest from the pinned tree, fail-closed."""
    expected = build(upstream)
    # The frozen 51-case RV64I manifest is regenerated by inventory.py and is
    # not touched here; only the F and D subdirectories are carved out of the
    # same pinned build so header parsing stays shared.
    sources = []
    for source in expected["sources"]:
        parts = Path(source["source"]).parts
        if len(parts) < 4 or parts[:2] != ("tests", "rv64i") or parts[2] not in DIRECTORIES:
            continue
        extensions, march, reason = DIRECTORIES[parts[2]]
        if (source["required_extensions"] != extensions or source["params"] != {"MXLEN": 64}
                or source["march"] != march):
            raise ValueError(f"unreviewed {parts[2]} source: {source['source']}")
        record = dict(source)
        record["disposition"] = "include"
        record["reason"] = reason
        record["coverage_consequence"] = (
            "Nontrapping RV64 F and D instruction coverage under --isa rv64imafd; "
            "failure remains a blocker.")
        sources.append(record)
    if not sources:
        raise ValueError("empty upstream F/D inventory")
    sources.sort(key=lambda s: s["source"])
    counts = {reason: sum(1 for s in sources if s["reason"] == reason)
              for _, _, reason in DIRECTORIES.values()}
    environment_headers = {
        f"tests/env/{path.name}": sha256(path)
        for path in sorted((upstream / "tests/env").iterdir()) if path.is_file()
    }
    return {
        "schema_version": 1,
        "status": expected["status"],
        "act4_commit": expected["act4_commit"],
        "scope": "all tracked tests/rv64i/F and tests/rv64i/D **/*.S at the pinned revision",
        "profile": PROFILE,
        # The frozen selection manifest is this profile's own document; the
        # accounting plan pins it instead of the unrelated RV64I proposal.
        "profile_document": str(MANIFEST),
        "counts": dict(sorted(counts.items())),
        "sources": sources,
        "environment_headers": environment_headers,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream", type=Path, default=Path(".a5/upstream"))
    parser.add_argument("--write", action="store_true", help="regenerate proposal for review, never freeze")
    args = parser.parse_args()
    actual = build_fd(args.upstream)
    selected(actual)
    if args.write:
        MANIFEST.write_text(json.dumps(actual, indent=2) + "\n")
    elif json.loads(MANIFEST.read_text()) != actual:
        raise ValueError("F/D selection differs from checked-in manifest")
    print(json.dumps({"status": actual["status"], "sources": len(actual["sources"]),
                      "counts": actual["counts"]}))


if __name__ == "__main__":
    main()
